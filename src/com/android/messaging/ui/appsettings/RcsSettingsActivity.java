package com.android.messaging.ui.appsettings;

import android.os.Bundle;
import android.view.MenuItem;

import androidx.appcompat.app.ActionBar;

import com.android.messaging.R;
import com.android.messaging.ui.BugleActionBarActivity;

/**
 * Activity displaying RCS Chat Features preferences and connection status.
 */
public class RcsSettingsActivity extends BugleActionBarActivity {

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        final ActionBar actionBar = getSupportActionBar();
        if (actionBar != null) {
            actionBar.setDisplayHomeAsUpEnabled(true);
            actionBar.setTitle(R.string.rcs_settings_title);
        }

        getSupportFragmentManager().beginTransaction()
                .replace(android.R.id.content, new RcsSettingsFragment())
                .commit();
    }

    @Override
    public boolean onOptionsItemSelected(MenuItem item) {
        if (item.getItemId() == android.R.id.home) {
            onBackPressed();
            return true;
        }
        return super.onOptionsItemSelected(item);
    }
}
